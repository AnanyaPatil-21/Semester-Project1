/* ================= SUBMIT COMPLAINT ================= */

function setupComplaintForm() {

    const form =
        document.getElementById("complaintForm");

    if (!form) {
        return;
    }

    form.addEventListener(
        "submit",
        function (event) {

            event.preventDefault();

            const category =
                document.getElementById(
                    "complaintCategory"
                ).value;

            const location =
                document.getElementById(
                    "location"
                ).value;

            const issue =
                document.getElementById(
                    "selectedIssue"
                ).value;

            const subject =
                document.getElementById(
                    "complaintSubject"
                ).value.trim();

            const description =
                document.getElementById(
                    "description"
                ).value.trim();

            const department =
                document.getElementById(
                    "department"
                ).value;

            if (!category || !location || !issue) {

                alert(
                    "Please select the complaint category, location and issue."
                );

                return;

            }

            if (!subject || !description) {

                alert(
                    "Please fill in all required complaint details."
                );

                return;

            }

            if (description.length > 300) {

                alert(
                    "Description cannot exceed 300 characters."
                );

                return;

            }


            const complaints =
                getComplaints();


            const newId =
                generateComplaintId(
                    complaints
                );


            const newComplaint = {

                id: newId,

                subject: subject,

                category: category,

                issue: issue,

                location: location,

                department: department,

                description: description,

                status: "Pending",

                date:
                    new Date()
                        .toISOString()
                        .split("T")[0],

                adminRemark: ""

            };


            complaints.unshift(
                newComplaint
            );


            saveComplaints(
                complaints
            );


            alert(
                `Complaint submitted successfully.\nComplaint ID: ${newId}`
            );


            form.reset();

            document.getElementById(
                "issueCards"
            ).innerHTML = "";

            document.getElementById(
                "location"
            ).innerHTML =
                '<option value="">Select Location</option>';

            document.getElementById(
                "selectedIssue"
            ).value = "";

            document.getElementById(
                "characterCount"
            ).textContent = "0";


            window.location.href =
                "my-complaints.html";

        }
    );

}


/* ================= GENERATE ID ================= */

function generateComplaintId(complaints) {

    let highestNumber = 1000;

    complaints.forEach(
        complaint => {

            const number =
                parseInt(
                    complaint.id.replace(
                        "CP",
                        ""
                    )
                );

            if (
                !isNaN(number) &&
                number > highestNumber
            ) {
                highestNumber = number;
            }

        }
    );

    return `CP${highestNumber + 1}`;

}


