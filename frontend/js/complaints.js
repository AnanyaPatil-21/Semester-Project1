/* ================= ADMIN COMPLAINTS ================= */

function loadAdminComplaints() {

    const container =
        document.getElementById(
            "adminComplaintsList"
        );

    if (!container) {
        return;
    }

    const complaints =
        getComplaints();

    const statusFilter =
        document.getElementById(
            "statusFilter"
        )?.value || "all";

    const categoryFilter =
        document.getElementById(
            "categoryFilter"
        )?.value || "all";

    const locationFilter =
        document.getElementById(
            "adminLocationFilter"
        )?.value || "all";

    const dateFilter =
        document.getElementById(
            "dateFilter"
        )?.value || "";


    const filtered =
        complaints.filter(
            complaint => {

                const statusMatch =
                    statusFilter === "all" ||
                    complaint.status === statusFilter;

                const categoryMatch =
                    categoryFilter === "all" ||
                    complaint.category === categoryFilter;

                const locationMatch =
                    locationFilter === "all" ||
                    complaint.location === locationFilter;

                const dateMatch =
                    !dateFilter ||
                    complaint.date === dateFilter;

                return (
                    statusMatch &&
                    categoryMatch &&
                    locationMatch &&
                    dateMatch
                );

            }
        );


    container.innerHTML = "";


    const count =
        document.getElementById(
            "complaintCount"
        );

    if (count) {

        count.textContent =
            `${filtered.length} Complaint${filtered.length !== 1 ? "s" : ""}`;

    }


    if (filtered.length === 0) {

        container.innerHTML = `
            <div class="empty-message">
                No complaints found.
            </div>
        `;

        return;

    }


    filtered.forEach(
        complaint => {

            const row =
                document.createElement("div");

            row.className =
                "complaint-row";


            row.innerHTML = `

                <div class="complaint-info">

                    <strong>
                        ${complaint.subject}
                    </strong>

                    <span>
                        ${complaint.id}
                        •
                        ${complaint.location}
                        •
                        ${complaint.date}
                    </span>

                </div>


                <span class="status ${getStatusClass(complaint.status)}">
                    ${complaint.status}
                </span>


                <a
                    href="complaint-details.html?id=${complaint.id}"
                    class="details-link"
                >
                    View Details
                </a>

            `;


            container.appendChild(row);

        }
    );

}


