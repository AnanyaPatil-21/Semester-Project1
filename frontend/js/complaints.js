/* ================= GET COMPLAINTS ================= */

function getComplaints() {

    const stored = localStorage.getItem(STORAGE_KEY);

    if (!stored) {

        localStorage.setItem(
            STORAGE_KEY,
            JSON.stringify(sampleComplaints)
        );

        return sampleComplaints;
    }

    return JSON.parse(stored);
}


/* ================= SAVE COMPLAINTS ================= */

function saveComplaints(complaints) {

    localStorage.setItem(
        STORAGE_KEY,
        JSON.stringify(complaints)
    );

}


/* ================= LOCATION FUNCTIONS ================= */

function getLocations(type) {

    if (type === "Lab") {
        return labLocations;
    }

    if (type === "Classroom") {
        return classroomLocations;
    }

    return otherLocations;

}


function populateLocations() {

    const locationSelect =
        document.getElementById("location");

    const type =
        document.getElementById("locationType")?.value;

    const department =
        document.getElementById("department")?.value;

    if (!locationSelect) {
        return;
    }

    locationSelect.innerHTML =
        '<option value="">Select Location</option>';

    if (!type) {
        return;
    }

    let locations = getLocations(type);

    if (
        department &&
        (type === "Lab" || type === "Classroom")
    ) {

        locations = locations.filter(
            location =>
                location.department === department ||
                location.department === ""
        );

    }

    locations.forEach(location => {

        const option =
            document.createElement("option");

        option.value = location.name;

        option.textContent = location.name;

        locationSelect.appendChild(option);

    });

}


/* ================= ISSUE CARDS ================= */

function populateIssueCards() {

    const issueContainer =
        document.getElementById("issueCards");

    const category =
        document.getElementById("complaintCategory")?.value;

    if (!issueContainer) {
        return;
    }

    issueContainer.innerHTML = "";

    const issues =
        issueCategories[category] || [];

    issues.forEach(issue => {

        const card =
            document.createElement("div");

        card.className = "issue-card";

        card.innerHTML = `
            <h3>${issue}</h3>
            <p>Select this issue</p>
        `;

        card.addEventListener("click", function () {

            document
                .querySelectorAll(".issue-card")
                .forEach(item => {
                    item.classList.remove("selected");
                });

            card.classList.add("selected");

            const selectedIssue =
                document.getElementById("selectedIssue");

            if (selectedIssue) {
                selectedIssue.value = issue;
            }

        });

        issueContainer.appendChild(card);

    });

}


