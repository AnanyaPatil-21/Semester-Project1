/* ================= ADMIN ACTIONS ================= */

function setupAdminActions(complaint) {

    const validateBtn =
        document.getElementById(
            "validateBtn"
        );

    const rejectBtn =
        document.getElementById(
            "rejectBtn"
        );

    const resolveBtn =
        document.getElementById(
            "resolveBtn"
        );

    const remarkInput =
        document.getElementById(
            "adminRemark"
        );


    if (validateBtn) {

        validateBtn.addEventListener(
            "click",
            function () {

                updateComplaintStatus(
                    complaint.id,
                    "In Progress",
                    remarkInput.value ||
                    "Complaint validated and forwarded for action."
                );

            }
        );

    }


    if (rejectBtn) {

        rejectBtn.addEventListener(
            "click",
            function () {

                updateComplaintStatus(
                    complaint.id,
                    "Rejected",
                    remarkInput.value ||
                    "Complaint rejected by administrator."
                );

            }
        );

    }


    if (resolveBtn) {

        resolveBtn.addEventListener(
            "click",
            function () {

                updateComplaintStatus(
                    complaint.id,
                    "Resolved",
                    remarkInput.value ||
                    "Complaint has been resolved."
                );

            }
        );

    }

}


/* ================= UPDATE STATUS ================= */

function updateComplaintStatus(
    complaintId,
    status,
    remark
) {

    const complaints =
        getComplaints();

    const complaint =
        complaints.find(
            item => item.id === complaintId
        );


    if (!complaint) {
        return;
    }


    complaint.status =
        status;

    complaint.adminRemark =
        remark;


    saveComplaints(
        complaints
    );


    alert(
        `Complaint ${complaintId} is now ${status}.`
    );


    window.location.reload();

}


/* ================= STATUS CLASS ================= */

function getStatusClass(status) {

    if (status === "Pending") {
        return "status-pending";
    }

    if (status === "In Progress") {
        return "status-progress";
    }

    if (status === "Resolved") {
        return "status-resolved";
    }

    if (status === "Rejected") {
        return "status-rejected";
    }

    return "";

}


